use std::collections::HashSet;

use serde_json::{Map, Value, json};

use crate::model::{Model, OptionModel, TypeKind};

const TEXT_HEADER: &str = "Generated by `cargo xtask generate-options`. Do not edit.";

pub(crate) fn render_types(model: &Model) -> String {
    let mut enums = model.enums.iter().collect::<Vec<_>>();
    enums.sort_by_key(|enum_model| &enum_model.name);

    let mut out = format!("// {TEXT_HEADER}\n\n");
    for enum_model in enums {
        out.push_str(&format!("export type {} = ", enum_model.name));
        out.push_str(
            &enum_model
                .variants
                .iter()
                .map(|variant| format!("\"{}\"", variant.value))
                .collect::<Vec<_>>()
                .join(" | "),
        );
        out.push_str(";\n\n");
    }

    out.push_str("export interface Options {\n");
    for option in &model.options {
        render_ts_field(&mut out, model, option, false);
    }
    out.push_str("}\n\nexport interface PartialOptions {\n");
    for option in &model.options {
        render_ts_field(&mut out, model, option, true);
    }
    out.push_str(
        "}\n\nexport type Config = Options;\n\nexport type PartialConfig = PartialOptions;\n\n\
         export type OptionKey = keyof Options;\n",
    );
    out
}

fn render_ts_field(out: &mut String, model: &Model, option: &OptionModel, optional: bool) {
    out.push_str("  /**\n");
    for line in option.description.trim().lines() {
        out.push_str(&format!("   * {line}\n"));
    }
    out.push_str("   */\n");
    let optional = if optional { "?" } else { "" };
    out.push_str(&format!(
        "  {}{}: {};\n",
        option.name,
        optional,
        ts_type(model, option)
    ));
}

fn ts_type<'a>(model: &'a Model, option: &OptionModel) -> &'a str {
    match option.kind {
        TypeKind::Boolean => "boolean",
        TypeKind::Integer | TypeKind::Float => "number",
        TypeKind::String => "string",
        TypeKind::Enum(index) => &model.enum_model(index).name,
    }
}

pub(crate) fn render_defaults(model: &Model) -> String {
    let mut defaults = Map::new();
    let mut options = model.options.iter().collect::<Vec<_>>();
    options.sort_by_key(|option| &option.name);
    for option in options {
        defaults.insert(option.name.clone(), option.default_json());
    }
    json_pretty(&Value::Object(defaults))
}

pub(crate) fn render_schema(model: &Model) -> String {
    let mut properties = Map::new();
    let mut options = model.options.iter().collect::<Vec<_>>();
    options.sort_by_key(|option| &option.name);
    for option in options {
        let mut property = Map::new();
        property.insert(
            "type".to_owned(),
            Value::String(
                match option.kind {
                    TypeKind::Boolean => "boolean",
                    TypeKind::Integer => "integer",
                    TypeKind::Float => "number",
                    TypeKind::String | TypeKind::Enum(_) => "string",
                }
                .to_owned(),
            ),
        );
        property.insert(
            "description".to_owned(),
            Value::String(option.description.trim().to_owned()),
        );
        property.insert("default".to_owned(), option.default_json());
        if let TypeKind::Enum(_) = option.kind {
            property.insert(
                "enum".to_owned(),
                Value::Array(
                    option
                        .choices(model)
                        .iter()
                        .map(|variant| Value::String(variant.value.clone()))
                        .collect(),
                ),
            );
        }
        properties.insert(option.name.clone(), Value::Object(property));
    }
    json_pretty(&json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Typstyle options",
        "type": "object",
        "additionalProperties": false,
        "properties": properties,
    }))
}

pub(crate) fn render_ui_schema(model: &Model) -> String {
    let mut groups = Vec::new();
    let mut seen = HashSet::new();
    for option in &model.options {
        if seen.insert(option.group.as_str()) {
            let members = model
                .options
                .iter()
                .filter(|candidate| candidate.group == option.group)
                .map(|candidate| Value::String(candidate.name.clone()))
                .collect::<Vec<_>>();
            groups.push(json!({
                "name": option.group,
                "options": members,
            }));
        }
    }

    let mut options = Map::new();
    let mut sorted = model.options.iter().collect::<Vec<_>>();
    sorted.sort_by_key(|option| &option.name);
    for option in sorted {
        options.insert(
            option.name.clone(),
            json!({
                "label": option.label,
                "description": option.description.trim(),
                "group": option.group,
                "widget": option.widget,
                "order": option.order,
                "default": option.default_json(),
            }),
        );
    }

    json_pretty(&json!({
        "groups": groups,
        "options": options,
    }))
}

pub(crate) fn render_markdown(model: &Model) -> String {
    let mut out = format!("# Formatter options\n\n{TEXT_HEADER}\n\n");
    out.push_str("| Option | Type | Default | Description |\n");
    out.push_str("| --- | --- | --- | --- |\n");
    for option in &model.options {
        let ty = match option.kind {
            TypeKind::Boolean => "boolean".to_owned(),
            TypeKind::Integer => "integer".to_owned(),
            TypeKind::Float => "number".to_owned(),
            TypeKind::String => "string".to_owned(),
            TypeKind::Enum(_) => option
                .choices(model)
                .iter()
                .map(|variant| variant.value.as_str())
                .collect::<Vec<_>>()
                .join(" \\| "),
        };
        out.push_str(&format!(
            "| `{}` | {} | `{}` | {} |\n",
            option.name,
            ty,
            option.default_display,
            option.description.trim()
        ));
    }
    out
}

fn json_pretty(value: &Value) -> String {
    let mut out = serde_json::to_string_pretty(value).expect("serializing JSON");
    out.push('\n');
    out
}
