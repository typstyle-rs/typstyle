//! Repository automation tasks.

use std::{
    collections::{BTreeMap, HashSet},
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result, bail};
use serde_json::{Map, Value, json};
use typstyle_core::{OptionKind, OptionSpec, Options};

fn main() -> Result<()> {
    let mut args = std::env::args().skip(1);
    match args.next().as_deref() {
        Some("generate-options") => {
            let check = args.next().as_deref() == Some("--check");
            if args.next().is_some() {
                bail!("usage: cargo xtask generate-options [--check]");
            }
            generate_options(check)
        }
        _ => bail!("usage: cargo xtask generate-options [--check]"),
    }
}

fn generate_options(check: bool) -> Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .context("xtask manifest has no repository root")?
        .to_owned();
    let output = root.join("packages/options/generated");

    let outputs = [
        ("types.ts", render_types()),
        ("defaults.json", render_defaults()?),
        ("schema.json", render_schema()?),
        ("ui-schema.json", render_ui_schema()?),
        ("options.md", render_markdown()),
    ];

    let mut stale = Vec::new();
    for (name, content) in outputs {
        let path = output.join(name);
        if check {
            match fs::read_to_string(&path) {
                Ok(existing) if existing == content => {}
                _ => stale.push(path),
            }
        } else {
            fs::create_dir_all(&output)
                .with_context(|| format!("creating {}", output.display()))?;
            fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
        }
    }

    if !stale.is_empty() {
        for path in stale {
            eprintln!("stale generated option artifact: {}", path.display());
        }
        bail!("run `cargo xtask generate-options` and commit the result");
    }
    if !check {
        println!("generated {}", output.display());
    }
    Ok(())
}

fn ts_type(spec: &OptionSpec) -> String {
    match spec.kind {
        OptionKind::Boolean => "boolean".to_owned(),
        OptionKind::Integer | OptionKind::Float => "number".to_owned(),
        OptionKind::String => "string".to_owned(),
        OptionKind::Enum => spec.type_name.to_owned(),
    }
}

fn render_types() -> String {
    let specs = Options::OPTION_SPECS;
    let mut enums: BTreeMap<&str, &[&str]> = BTreeMap::new();
    for spec in specs {
        if matches!(spec.kind, OptionKind::Enum) {
            enums.insert(spec.type_name, spec.choices);
        }
    }

    let mut out = String::from("// Generated by `cargo xtask generate-options`. Do not edit.\n\n");
    for (name, choices) in enums {
        out.push_str(&format!("export type {name} = "));
        out.push_str(
            &choices
                .iter()
                .map(|choice| format!("\"{choice}\""))
                .collect::<Vec<_>>()
                .join(" | "),
        );
        out.push_str(";\n\n");
    }

    out.push_str("export interface Options {\n");
    for spec in specs {
        render_ts_field(&mut out, spec, false);
    }
    out.push_str("}\n\nexport interface PartialOptions {\n");
    for spec in specs {
        render_ts_field(&mut out, spec, true);
    }
    out.push_str(
        "}\n\nexport type Config = Options;\n\nexport type PartialConfig = PartialOptions;\n\n\
         export type OptionKey = keyof Options;\n",
    );
    out
}

fn render_ts_field(out: &mut String, spec: &OptionSpec, optional: bool) {
    out.push_str("  /**\n");
    for line in spec.description.lines() {
        out.push_str(&format!("   * {line}\n"));
    }
    out.push_str("   */\n");
    let optional = if optional { "?" } else { "" };
    out.push_str(&format!("  {}{}: {};\n", spec.key, optional, ts_type(spec)));
}

fn json_pretty(value: &Value) -> String {
    let mut out = serde_json::to_string_pretty(value).expect("serializing JSON");
    out.push('\n');
    out
}

fn render_defaults() -> Result<String> {
    Ok(json_pretty(&serde_json::to_value(Options::default())?))
}

fn render_schema() -> Result<String> {
    let defaults = serde_json::to_value(Options::default())?;
    let mut properties = Map::new();
    for spec in Options::OPTION_SPECS {
        let mut property = Map::new();
        property.insert(
            "type".to_owned(),
            Value::String(
                match spec.kind {
                    OptionKind::Boolean => "boolean",
                    OptionKind::Integer => "integer",
                    OptionKind::Float => "number",
                    OptionKind::String | OptionKind::Enum => "string",
                }
                .to_owned(),
            ),
        );
        property.insert(
            "description".to_owned(),
            Value::String(spec.description.to_owned()),
        );
        if let Some(default) = defaults.get(spec.key) {
            property.insert("default".to_owned(), default.clone());
        }
        if matches!(spec.kind, OptionKind::Enum) {
            property.insert(
                "enum".to_owned(),
                Value::Array(
                    spec.choices
                        .iter()
                        .map(|choice| Value::String((*choice).to_owned()))
                        .collect(),
                ),
            );
        }
        properties.insert(spec.key.to_owned(), Value::Object(property));
    }
    Ok(json_pretty(&json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Typstyle options",
        "type": "object",
        "additionalProperties": false,
        "properties": properties,
    })))
}

fn render_ui_schema() -> Result<String> {
    let defaults = serde_json::to_value(Options::default())?;
    let mut groups: Vec<Value> = Vec::new();
    let mut seen = HashSet::new();
    let mut options = Map::new();

    for spec in Options::OPTION_SPECS {
        if seen.insert(spec.group) {
            let members = Options::OPTION_SPECS
                .iter()
                .filter(|candidate| candidate.group == spec.group)
                .map(|candidate| Value::String(candidate.key.to_owned()))
                .collect::<Vec<_>>();
            groups.push(json!({
                "name": spec.group,
                "options": members,
            }));
        }

        let widget = spec.widget.unwrap_or(match spec.kind {
            OptionKind::Boolean => "checkbox",
            OptionKind::Integer | OptionKind::Float => "number",
            OptionKind::String => "text",
            OptionKind::Enum => "select",
        });
        options.insert(
            spec.key.to_owned(),
            json!({
                "label": spec.label,
                "description": spec.description,
                "group": spec.group,
                "widget": widget,
                "order": spec.order,
                "default": defaults.get(spec.key),
            }),
        );
    }

    Ok(json_pretty(&json!({
        "groups": groups,
        "options": options,
    })))
}

fn render_markdown() -> String {
    let defaults = serde_json::to_value(Options::default()).expect("serializing defaults");
    let mut out = String::from(
        "# Formatter options\n\nGenerated by `cargo xtask generate-options`. Do not edit.\n\n",
    );
    out.push_str("| Option | Type | Default | Description |\n");
    out.push_str("| --- | --- | --- | --- |\n");
    for spec in Options::OPTION_SPECS {
        let ty = match spec.kind {
            OptionKind::Boolean => "boolean".to_owned(),
            OptionKind::Integer => "integer".to_owned(),
            OptionKind::Float => "number".to_owned(),
            OptionKind::String => "string".to_owned(),
            OptionKind::Enum => spec.choices.join(" \\| "),
        };
        let default = defaults
            .get(spec.key)
            .map(format_default)
            .unwrap_or_default();
        out.push_str(&format!(
            "| `{}` | {} | `{}` | {} |\n",
            spec.key, ty, default, spec.description
        ));
    }
    out
}

fn format_default(value: &Value) -> String {
    match value {
        Value::String(value) => value.clone(),
        other => other.to_string(),
    }
}
